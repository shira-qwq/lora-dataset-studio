from __future__ import annotations

import ast
import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable


REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.dependency_catalog import (  # noqa: E402
    OPTIONAL_IMPORT_TO_PACKAGE,
    PROJECT_ROOT_PACKAGES,
    STD_LIB_MODULES,
    package_for_import,
)


SKIP_DIRS = {
    ".git",
    ".venv",
    "venv",
    "env",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    "node_modules",
    "dist",
    "build",
    ".runtime",
    ".setup",
    "outputs",
    "output",
    "exports",
    "analysis_exports",
    "organized_exports",
    "job_outputs",
    "runs",
    "tmp",
    "temp",
    "test_smoke_output",
}


@dataclass
class AuditResult:
    scanned_files: list[Path] = field(default_factory=list)
    runtime_sources: dict[str, set[str]] = field(default_factory=dict)
    dev_sources: dict[str, set[str]] = field(default_factory=dict)
    optional_sources: dict[str, set[str]] = field(default_factory=dict)
    unknown_sources: dict[str, set[str]] = field(default_factory=dict)


def _should_skip(path: Path) -> bool:
    return any(part in SKIP_DIRS for part in path.parts)


def iter_python_files(root: Path = REPO_ROOT) -> list[Path]:
    files: list[Path] = []
    for path in root.rglob("*.py"):
        if path.is_file() and not _should_skip(path.relative_to(root)):
            files.append(path)
    return sorted(files)


def _is_optional_source(path: Path) -> bool:
    parts = path.as_posix().lower()
    return "gui_main.py" in parts or "/gui/" in parts


def _file_group(path: Path, root: Path = REPO_ROOT) -> str:
    rel = path.relative_to(root).as_posix()
    if rel.startswith("tests/"):
        return "dev"
    if rel.startswith("tools/") or rel.startswith("scripts/"):
        return "dev"
    if _is_optional_source(path):
        return "optional"
    if any(rel.startswith(f"{pkg}/") for pkg in PROJECT_ROOT_PACKAGES if pkg not in {"tests", "tools", "scripts"}):
        return "runtime"
    return "runtime"


def _collect_imports(path: Path) -> set[str]:
    imports: set[str] = set()
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError:
        return imports

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                root = alias.name.split(".")[0]
                imports.add(root)
        elif isinstance(node, ast.ImportFrom):
            if node.level and node.level > 0:
                continue
            if not node.module:
                continue
            root = node.module.split(".")[0]
            imports.add(root)
    return imports


def scan_repository(root: Path = REPO_ROOT) -> AuditResult:
    result = AuditResult()
    for path in iter_python_files(root):
        result.scanned_files.append(path)
        group = _file_group(path, root)
        for module_name in _collect_imports(path):
            if module_name in STD_LIB_MODULES:
                continue
            if module_name in PROJECT_ROOT_PACKAGES:
                continue
            package = package_for_import(module_name)
            if package is None:
                result.unknown_sources.setdefault(module_name, set()).add(path.relative_to(root).as_posix())
                continue
            if module_name in OPTIONAL_IMPORT_TO_PACKAGE:
                result.optional_sources.setdefault(package, set()).add(path.relative_to(root).as_posix())
                continue
            if group == "runtime":
                result.runtime_sources.setdefault(package, set()).add(path.relative_to(root).as_posix())
            elif group == "optional":
                result.optional_sources.setdefault(package, set()).add(path.relative_to(root).as_posix())
            else:
                result.dev_sources.setdefault(package, set()).add(path.relative_to(root).as_posix())
    return result


def _format_requirements(packages: Iterable[str]) -> str:
    lines = ["# Auto-generated by scripts/audit_python_deps.py"]
    for package in sorted(dict.fromkeys(packages), key=str.lower):
        lines.append(package)
    lines.append("")
    return "\n".join(lines)


def render_audit_report(result: AuditResult, root: Path = REPO_ROOT) -> str:
    runtime_packages = sorted(result.runtime_sources, key=str.lower)
    dev_packages = sorted(result.dev_sources, key=str.lower)
    optional_packages = sorted(result.optional_sources, key=str.lower)

    lines = [
        "# DEPENDENCY_AUDIT_CN",
        "",
        f"- 扫描文件数: {len(result.scanned_files)}",
        f"- 运行时包数: {len(runtime_packages)}",
        f"- 开发/测试包数: {len(dev_packages)}",
        f"- 可选包数: {len(optional_packages)}",
        "",
        "## 运行时依赖",
    ]
    for package in runtime_packages:
        sources = ", ".join(sorted(result.runtime_sources[package]))
        lines.append(f"- `{package}`: {sources}")

    lines.extend(["", "## 开发/测试依赖"])
    for package in dev_packages:
        sources = ", ".join(sorted(result.dev_sources[package]))
        lines.append(f"- `{package}`: {sources}")

    lines.extend(["", "## 可选依赖"])
    for package in optional_packages:
        sources = ", ".join(sorted(result.optional_sources[package]))
        lines.append(f"- `{package}`: {sources}")

    if result.unknown_sources:
        lines.extend(["", "## 未映射导入"])
        for module_name in sorted(result.unknown_sources):
            sources = ", ".join(sorted(result.unknown_sources[module_name]))
            lines.append(f"- `{module_name}`: {sources}")

    lines.extend([
        "",
        "## 说明",
        "- `cv2` 映射为 `opencv-python`。",
        "- `PIL` 映射为 `Pillow`。",
        "- `sklearn` 映射为 `scikit-learn`。",
        "- `umap` 映射为 `umap-learn`。",
        "- `PyQt6` 只在 GUI 入口使用，不写入运行时 requirements。",
        "- `optuna` 只在工具/实验路径出现，视为可选依赖。",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Audit Python dependencies from source imports")
    parser.add_argument("--repo-root", default=str(REPO_ROOT))
    args = parser.parse_args()
    root = Path(args.repo_root).resolve()

    result = scan_repository(root)
    runtime_packages = sorted(result.runtime_sources, key=str.lower)
    requirements_text = _format_requirements(runtime_packages)

    requirements_generated = root / "requirements.generated.txt"
    requirements_generated.write_text(requirements_text, encoding="utf-8")

    report_path = root / "DEPENDENCY_AUDIT_CN.md"
    report_path.write_text(render_audit_report(result, root), encoding="utf-8")

    print(str(requirements_generated))
    print(str(report_path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
